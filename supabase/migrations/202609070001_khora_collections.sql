INSERT INTO public.collection_items(collection_id, product_id, sort_order)
SELECT collection.id, visible_product.id,
  row_number() OVER (ORDER BY visible_product.name, visible_product.id)::integer
FROM public.collections collection
CROSS JOIN LATERAL (
  SELECT p.id, cb.name
  FROM public.products p
  JOIN public.code_base cb ON cb.id = p.code_base_id
  LEFT JOIN public.categories category ON category.id = p.category_id
  WHERE p.active = 1
    AND p.store_published = true
    AND p.sale_price_cents > 0
    AND (p.category_id IS NULL OR lower(trim(category.name)) = 'colección khora')
) visible_product
WHERE collection.slug = 'coleccion-khora'
ON CONFLICT (collection_id, product_id) DO NOTHING;

