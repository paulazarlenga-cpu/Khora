-- Colecciones comerciales independientes de las categorías del catálogo.
-- Un producto (incluidos los productos de tipo COMBO) puede pertenecer a varias.
CREATE TABLE IF NOT EXISTS public.collections (
  id bigint generated by default as identity primary key,
  name text NOT NULL CHECK (length(trim(name)) > 0),
  slug text NOT NULL UNIQUE CHECK (length(trim(slug)) > 0),
  description text,
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED')),
  visible_in_store boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 1 CHECK (sort_order >= 1),
  created_at timestamptz NOT NULL DEFAULT current_timestamp,
  updated_at timestamptz NOT NULL DEFAULT current_timestamp
);

CREATE UNIQUE INDEX IF NOT EXISTS collections_name_ci_uq
  ON public.collections (lower(trim(name)));

CREATE INDEX IF NOT EXISTS collections_store_order_idx
  ON public.collections (sort_order, name, id)
  WHERE status = 'PUBLISHED' AND visible_in_store = true;

CREATE TABLE IF NOT EXISTS public.collection_items (
  id bigint generated by default as identity primary key,
  collection_id bigint NOT NULL REFERENCES public.collections(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  sort_order integer NOT NULL CHECK (sort_order >= 1),
  created_at timestamptz NOT NULL DEFAULT current_timestamp,
  UNIQUE (collection_id, product_id)
);

CREATE INDEX IF NOT EXISTS collection_items_order_idx
  ON public.collection_items (collection_id, sort_order, id);
CREATE INDEX IF NOT EXISTS collection_items_product_idx
  ON public.collection_items (product_id, collection_id);

ALTER TABLE public.collections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.collection_items ENABLE ROW LEVEL SECURITY;

